let current = 'tr';

export function pickInitialLang(saved) {
  if (saved && STRINGS[saved]) return saved;
  const nav = (navigator.language || 'tr').slice(0, 2).toLowerCase();
  return STRINGS[nav] ? nav : 'tr';
}

export function setLang(code) {
  current = STRINGS[code] ? code : 'tr';
  document.documentElement.lang = current;
}
export const getLang = () => current;

export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.tr[key] ?? key;
  return s
    .replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_, k, one, many) => (Number(vars[k]) === 1 ? one : many)) // {n|tekil|çoğul}
    .replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** HTML'deki data-i18n (metin) ve data-i18n-ph (placeholder) alanlarını doldurur. */
export function applyI18n(root = document, vars = {}) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n, vars); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh, vars); });
  root.querySelectorAll('[data-i18n-label]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nLabel, vars)); });
}
